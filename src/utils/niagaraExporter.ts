import { NiagaraProgram } from '../types/niagara';

export function exportToNiagaraXml(program: NiagaraProgram): string {
  const blocks = program.blocks || [];
  const links = program.links || [];

  const blocksXml = blocks
    .map((b) => {
      const typeParts = (b.palette || 'kitControl').split(':');
      const moduleName = typeParts[0] || 'kitControl';
      return `    <!-- Block: ${b.name} (${b.type}) -->
    <p n="${b.name}" t="${moduleName}:${b.type}" m="${moduleName}">
      <p n="wsAnnotation" t="baja:WsAnnotation" v="2,2,${Math.round(b.x)},${Math.round(b.y)},0"/>
      ${Object.entries(b.properties || {})
        .map(([k, v]) => `<p n="${k}" v="${v}"/>`)
        .join('\n      ')}
    </p>`;
    })
    .join('\n\n');

  const linksXml = links
    .map((l) => {
      const sourceBlock = blocks.find((b) => b.id === l.fromBlockId);
      const targetBlock = blocks.find((b) => b.id === l.toBlockId);
      const sourceName = sourceBlock ? sourceBlock.name : l.fromBlockId;
      const targetName = targetBlock ? targetBlock.name : l.toBlockId;
      return `    <!-- Link: ${sourceName}.${l.fromSlot} -> ${targetName}.${l.toSlot} -->
    <link from="${sourceName}" fromSlot="${l.fromSlot}" to="${targetName}" toSlot="${l.toSlot}"/>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Niagara Tridium Wire Sheet Program Export -->
<!-- Generated by Tridium Niagara Wire Sheet AI Builder -->
<!-- Program: ${program.title || 'Untitled'} -->
<bajaObjectGraph version="4.0" rever="4.10.0">
  <p n="WireSheetLogic" t="baja:Folder">
${blocksXml}

${linksXml}
  </p>
</bajaObjectGraph>`;
}

export function generatePrintableGuide(program: NiagaraProgram): string {
  const blocks = program.blocks || [];
  const links = program.links || [];
  const rebuildSteps = program.rebuildSteps || [];

  const dateStr = new Date().toLocaleDateString();
  const stepsHtml = rebuildSteps
    .map(
      (s) => `
    <div class="step-card">
      <div class="step-header">
        <span class="step-badge">Step ${s.stepNumber}</span>
        <span class="step-phase">[Phase: ${(s.phase || 'logic').toUpperCase()}]</span>
        <span class="step-title">${s.title}</span>
      </div>
      <p class="step-desc">${s.instruction}</p>
      ${s.paletteName ? `<div class="step-meta"><strong>Palette:</strong> <code>${s.paletteName}</code></div>` : ''}
      ${s.componentType ? `<div class="step-meta"><strong>Component Type:</strong> <code>${s.componentType}</code></div>` : ''}
      ${s.slotDetails ? `<div class="step-meta"><strong>Details / Slots:</strong> <code>${s.slotDetails}</code></div>` : ''}
      ${s.tips ? `<div class="step-tip">💡 <strong>Tridium Tip:</strong> ${s.tips}</div>` : ''}
    </div>`
    )
    .join('\n');

  const linksHtml = links
    .map((l) => {
      const source = blocks.find((b) => b.id === l.fromBlockId)?.name || l.fromBlockId;
      const target = blocks.find((b) => b.id === l.toBlockId)?.name || l.toBlockId;
      return `<tr>
      <td><code>${source}</code></td>
      <td><span class="slot-badge out">${l.fromSlot}</span></td>
      <td>➔</td>
      <td><code>${target}</code></td>
      <td><span class="slot-badge in">${l.toSlot}</span></td>
      <td>${l.signalType || 'standard'}</td>
    </tr>`;
    })
    .join('\n');

  return `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>Niagara Manual Build Guide - ${program.title}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; line-height: 1.5; color: #1e293b; max-width: 900px; margin: 0 auto; padding: 32px 20px; background: #f8fafc; }
    h1 { color: #0f172a; margin-bottom: 4px; font-size: 26px; }
    .subtitle { color: #64748b; font-size: 15px; margin-top: 0; margin-bottom: 24px; }
    .section-title { font-size: 18px; font-weight: 700; color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; margin-top: 32px; }
    .soo-box { background: #ffffff; border: 1px solid #cbd5e1; border-radius: 8px; padding: 16px; white-space: pre-wrap; font-size: 14px; color: #334155; }
    .step-card { background: #ffffff; border: 1px solid #cbd5e1; border-radius: 8px; padding: 16px; margin-bottom: 12px; }
    .step-header { display: flex; align-items: center; gap: 10px; margin-bottom: 8px; }
    .step-badge { background: #0284c7; color: #ffffff; padding: 2px 8px; border-radius: 4px; font-size: 12px; font-weight: 700; }
    .step-phase { font-size: 11px; font-weight: 600; color: #64748b; }
    .step-title { font-weight: 700; font-size: 15px; color: #0f172a; }
    .step-desc { margin: 6px 0; font-size: 14px; }
    .step-meta { font-size: 13px; color: #475569; margin: 4px 0; }
    .step-tip { background: #f0fdf4; border: 1px solid #bbf7d0; color: #166534; padding: 8px; border-radius: 6px; font-size: 13px; margin-top: 8px; }
    code { background: #f1f5f9; padding: 2px 6px; border-radius: 4px; font-size: 12px; font-family: monospace; }
    table { width: 100%; border-collapse: collapse; background: #ffffff; border: 1px solid #cbd5e1; border-radius: 8px; overflow: hidden; margin-top: 12px; }
    th { background: #f1f5f9; text-align: left; padding: 10px 12px; font-size: 13px; font-weight: 600; color: #475569; border-bottom: 1px solid #cbd5e1; }
    td { padding: 10px 12px; font-size: 13px; border-bottom: 1px solid #f1f5f9; }
    .slot-badge { padding: 2px 6px; border-radius: 4px; font-size: 11px; font-weight: 600; font-family: monospace; }
    .slot-badge.out { background: #fee2e2; color: #991b1b; }
    .slot-badge.in { background: #dbeafe; color: #1e40af; }
    @media print { body { background: #fff; padding: 0; } }
  </style>
</head>
<body>
  <h1>${program.title}</h1>
  <p class="subtitle">Tridium Niagara Workbench Recreation Blueprint • Generated on ${dateStr}</p>

  <h2 class="section-title">1. Sequence of Operation (SOO)</h2>
  <div class="soo-box">${program.sequenceOfOperation}</div>

  <h2 class="section-title">2. Step-by-Step Workbench Build Instructions</h2>
  ${stepsHtml}

  <h2 class="section-title">3. Niagara Link Wiring Table (${program.links.length} Links)</h2>
  <table>
    <thead>
      <tr>
        <th>Source Component</th>
        <th>Source Slot</th>
        <th></th>
        <th>Target Component</th>
        <th>Target Slot</th>
        <th>Signal Type</th>
      </tr>
    </thead>
    <tbody>
      ${linksHtml}
    </tbody>
  </table>
</body>
</html>`;
}
